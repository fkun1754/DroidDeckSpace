package com.droiddeck.launcher.runtime

import android.content.Context
import com.droiddeck.launcher.runtime.container.SuShell
import java.io.File

/**
 * A KernelSU service.d script is the only reliable boot start: Android does not deliver
 * BOOT_COMPLETED to a force-stopped app, and the runtime rootfs lives in credential-encrypted
 * storage, so DroidSpaces' pre-unlock autoboot cannot see it either.
 */
object BootServiceScript {
    private const val TARGET = "/data/adb/service.d/droiddeckspace-boot.sh"
    private const val MODULE = "/data/adb/modules/droiddeckspace-boot"
    private const val MODULE_DISABLE = "$MODULE/disable"

    fun install(context: Context, container: String): String? {
        // Prefer the KernelSU module; the app only toggles its disable flag.
        val module = SuShell.exec(
            "if [ -f $MODULE/module.prop ]; then rm -f $MODULE_DISABLE; rm -f $TARGET; echo module; else echo legacy; fi",
            15_000,
        )
        if (module.ok() && module.stdout.contains("module")) return null
        val pkg = context.packageName
        val files = "/data/user/0/$pkg/files"
        val script = """
            #!/system/bin/sh
            # Generated by DroidDeckSpace: optional boot start of the Linux runtime.
            PKG=$pkg
            CT='$container'
            CFG="/data/local/Droidspaces/Containers/${'$'}CT/container.config"
            DST=/data/local/Droidspaces/bin/droidspaces
            LOG=/data/local/tmp/droiddeckspace-boot.log
            log() { echo "${'$'}(date '+%F %T') ${'$'}*" >> "${'$'}LOG"; }
            log "waiting for boot"
            i=0
            while [ "${'$'}(getprop sys.boot_completed)" != "1" ] && [ ${'$'}i -lt 180 ]; do sleep 2; i=${'$'}((i+1)); done
            i=0
            while [ ! -d "/data/user/0/${'$'}PKG/files" ] && [ ${'$'}i -lt 120 ]; do sleep 2; i=${'$'}((i+1)); done
            [ -d "/data/user/0/${'$'}PKG/files" ] || { log "app data not available"; exit 0; }
            [ -x "${'$'}DST" ] || { log "droidspaces missing"; exit 0; }
            [ -f "${'$'}CFG" ] || { log "container config missing: ${'$'}CFG"; exit 0; }
            if "${'$'}DST" -n "${'$'}CT" pid 2>/dev/null | grep -qE '^[0-9]+'; then log "container already running"; exit 0; fi
            ENV="/data/user/0/${'$'}PKG/files/container/session.env"
            [ -f "${'$'}ENV" ] || { log "session env missing"; exit 0; }
            # Boot into a maintenance container (no game/desktop session).
            TMP="${'$'}ENV.new"
            grep -v -E '^(DD_MODE|DD_SESSION)=' "${'$'}ENV" > "${'$'}TMP" 2>/dev/null || cp "${'$'}ENV" "${'$'}TMP"
            printf "%s\n" "DD_MODE='service'" "DD_SESSION='service'" >> "${'$'}TMP"
            chown 10490:10490 "${'$'}TMP" 2>/dev/null
            mv -f "${'$'}TMP" "${'$'}ENV"
            log "starting ${'$'}CT"
            "${'$'}DST" --config "${'$'}CFG" start >>"${'$'}LOG" 2>&1
            log "start rc=${'$'}?"
        """.trimIndent() + "\n"
        val local = File(context.filesDir, "droiddeckspace-boot.sh")
        return runCatching {
            local.writeText(script)
            val result = SuShell.exec(
                "mkdir -p /data/adb/service.d && cp ${'$'}{local.absolutePath} $TARGET && chmod 755 $TARGET",
                20_000,
            )
            if (result.ok()) null else "写入开机脚本失败：" + result.combined()
        }.getOrElse { "写入开机脚本失败：" + (it.message ?: it) }
    }

    fun remove(): String? {
        val result = SuShell.exec(
            "if [ -d $MODULE ]; then touch $MODULE_DISABLE; fi; rm -f $TARGET", 10_000,
        )
        return if (result.ok()) null else "删除开机脚本失败：" + result.combined()
    }
}
